import assert from 'node:assert/strict';
import { PRODUCTS, STORAGE_CONFIG } from './data.mjs';
import { emptyState, normalizeState, toggleFavorite, validateRequest,
         pickupDateError, addFavoriteDetails } from './logic.mjs';

const valid={name:'Test Customer',email:'test@example.com',date:'2026-10-19',type:'preorder',details:'Two Signature Loaves for pickup at 10 a.m.',allergy:''};
const today='2026-10-18';
assert.equal(PRODUCTS.length,8);
assert.deepEqual(normalizeState('{broken preferences'),emptyState());
assert.deepEqual(normalizeState('null'),emptyState());
assert.deepEqual(normalizeState('[]'),emptyState());
assert.deepEqual(normalizeState('{"favorites":["cookies","unknown","cookies",null,"constructor"],"category":"breads"}'),{version:1,favorites:['cookies'],category:'breads'});
assert.equal(normalizeState('{"favorites":[],"category":"constructor"}').category,'all');
let state=toggleFavorite(emptyState(),'signature-loaf');
state={...state,category:'breads'};
const fakeStorage=new Map();fakeStorage.set(STORAGE_CONFIG.key,JSON.stringify(state));
const restored=normalizeState(fakeStorage.get(STORAGE_CONFIG.key));
assert.deepEqual(restored.favorites,['signature-loaf']);assert.equal(restored.category,'breads');
assert.deepEqual(toggleFavorite(restored,'signature-loaf').favorites,[]);
assert.deepEqual(toggleFavorite(restored,'unknown'),restored);
assert.deepEqual(validateRequest(valid,today),{});
assert.match(validateRequest({...valid,name:' '},today).name,/2 characters/);
assert.match(validateRequest({...valid,email:'bad-email'},today).email,/valid email/);
assert.match(validateRequest({...valid,details:'tiny'},today).details,/10 characters/);
assert.match(validateRequest({...valid,date:''},today).date,/pickup date/);
assert.equal(validateRequest({...valid,type:'question',date:''},today).date,undefined);
assert.match(validateRequest({...valid,type:'constructor'},today).type,/request type/);
assert.match(pickupDateError('2026-10-17',true,today),/later/);
assert.match(pickupDateError('2026-10-18',true,today),/Sunday/);
assert.match(pickupDateError('2026-02-31',true,'2026-01-01'),/valid/);
assert.equal(pickupDateError('2026-10-19',true,today),'');
assert.match(validateRequest({...valid,details:'x'.repeat(1501)},today).details,/1500/);
assert.match(validateRequest({...valid,allergy:'x'.repeat(501)},today).allergy,/500/);
const existing='Please advise about ingredients.';
const prefill=addFavoriteDetails(existing,restored.favorites);
assert.equal(prefill.added,true);assert.ok(prefill.text.startsWith(existing));assert.match(prefill.text,/Signature Loaf/);
assert.equal(addFavoriteDetails(prefill.text,restored.favorites).reason,'duplicate');
assert.equal(addFavoriteDetails('x'.repeat(1499),restored.favorites).reason,'length');
assert.equal(addFavoriteDetails(existing,[]).text,existing);
console.log('Passed storage normalization and simulated save/reload checks, favorite toggling, category restoration, contact prefill, duplicate prevention, and required/email/length/date validation checks.');
console.log('Browser event handling, real localStorage, layout, and screenshots remain unverified.');
